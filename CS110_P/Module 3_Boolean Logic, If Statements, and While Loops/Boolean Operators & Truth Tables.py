# Boolean Operators & Truth Tables

#AND Operator
#A     B     A and B
#--------------------
#True  True  True
#True  False False
#False True  False
#False False False

#print(True and True)   #Output: True
#print(True and False)  #Output: False

#OR Operator
#A     B     A or B
#--------------------
#True  True  True
#True  False True
#False True  True
#False False False

#print(True or True)    #Output: True
#print(True or False)   #Output: True

#NOT Operator

#Toggles true -> false or false -> true
#print(not True)         #Output: False
#print(not False)        #Output: True

#XOR Operator
#A     B     A xor B
#--------------------
#True  True  False
#True  False True
#False True  True
#False False False

#print(True ^ True)     #Output: False
#print(True ^ False)    #Output: True

